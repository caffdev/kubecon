#!/usr/bin/env node
// Generate the tool-index appendix for a deck from <deck>/assets/tools.json:
//   slides/tool-index.html      the divider: every tool as a drawer tab
//   slides/ti-<id>.html         one catalogue card per tool
//   deck.json                   a "with-index" draft = main + the appendix (main stays default)
//   narrative.md                an "Appendix" beat for each generated slide, if missing
// Re-runnable: it overwrites the generated slides and rewrites the appendix part of the draft.
//
//   node docs/decks/_shared/gen/tool-cards.mjs path1-deployments "Path 1"
import fs from 'node:fs';
import path from 'node:path';

const [deck, label = deck] = process.argv.slice(2);
if (!deck) { console.error('usage: tool-cards.mjs <deck> [label]'); process.exit(1); }
const root = new URL('../../', import.meta.url).pathname;
const dir = path.join(root, deck);
const tools = JSON.parse(fs.readFileSync(path.join(dir, 'assets/tools.json'), 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const page = (title, body, notes) => `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <link rel="stylesheet" href="../../_kit/runtime/slide.css">
  <link rel="stylesheet" href="../theme/theme.css">
  <link rel="stylesheet" href="../../_shared/catalogue.css">
</head>
<body>
  <!-- generated by _shared/gen/tool-cards.mjs from assets/tools.json; edit the JSON, not this file -->
${body}
  <aside class="notes">
${notes}
  </aside>

  <script src="../../_kit/runtime/slide.js"></script>
</body>
</html>
`;

// the divider
const tabs = tools.map((t) => `      <p class="tab">${esc(t.name)}<span class="${t.status.toLowerCase()}">${t.status.toUpperCase()}</span></p>`).join('\n');
fs.writeFileSync(path.join(dir, 'slides/tool-index.html'), page('Tool index', `  <main class="slide">
    <h2>Every tool we named, one card each, with where we stand.</h2>
    <div class="drawer">
${tabs}
    </div>
  </main>`, `    The appendix: every tool this path names gets one catalogue card. What it is, what sets it apart, and where we stand, with the status stamped on it: adopt, trial, decide or watch. This part is for reading afterwards, not for presenting.`));

// the cards
for (const t of tools) {
  const body = `  <main class="slide cat-slide">
    <div class="cat-card">
      <p class="cat-head"><span>${esc(label)}, ${esc(t.cat)}</span><span>GOALS ${esc(t.goals)}</span></p>
      <h2 class="cat-title">${esc(t.name)}</h2>
      <p class="cat-lede">${esc(t.lede)}</p>
      <div class="cat-fields">
        <div class="cat-field"><p class="cat-k">WHAT IT IS</p><p class="cat-v">${esc(t.what)}</p></div>
        <div class="cat-field"><p class="cat-k">WHAT SETS IT APART</p><p class="cat-v">${esc(t.apart)}</p></div>
        <div class="cat-field wide stand"><p class="cat-k">WHERE WE STAND</p><p class="cat-v">${esc(t.stand)}</p></div>
      </div>
      <p class="cat-src">${esc(t.src)}</p>
      <p class="cat-stamp ${t.status.toLowerCase()}" aria-hidden="true">${t.status.toUpperCase()}</p>
    </div>
  </main>`;
  fs.writeFileSync(path.join(dir, `slides/ti-${t.id}.html`), page(t.name, body, `    ${esc(t.name)}: ${esc(t.lede)} Where we stand: ${esc(t.stand)}\n\n    ${esc(t.note)}`));
}

// the draft
const dj = JSON.parse(fs.readFileSync(path.join(dir, 'deck.json'), 'utf8'));
dj.drafts['with-index'] = [...dj.drafts.main, 'tool-index', ...tools.map((t) => `ti-${t.id}`)];
fs.writeFileSync(path.join(dir, 'deck.json'), JSON.stringify(dj, null, 2) + '\n');

// narrative beats, appended once
const np = path.join(dir, 'narrative.md');
let nar = fs.readFileSync(np, 'utf8');
if (!nar.includes('### tool-index')) {
  nar += `\n## Appendix: the tool index\n\nGenerated by \`_shared/gen/tool-cards.mjs\` from \`assets/tools.json\` and used only by the\n\`with-index\` draft. One catalogue card per tool named in this deck; the cards are for\nreading afterwards, not for presenting. Edit the JSON and re-run the script.\n\n### tool-index\n\n- **Act:** Appendix\n- **Job:** open the reference section and show every tool at a glance\n- **Headline:** Every tool we named, one card each, with where we stand.\n- **Visual:** a catalogue drawer of tabs, each with its status\n- **Energy:** 1\n- **Into next:** one card per tool follows.\n`;
  for (const t of tools) {
    nar += `\n### ti-${t.id}\n\n- **Act:** Appendix\n- **Job:** the reference card for ${t.name}\n- **Headline:** ${t.lede}\n- **Visual:** a catalogue card: what it is, what sets it apart, where we stand, stamped ${t.status.toUpperCase()}\n- **Energy:** 1\n- **Into next:** the next card.\n`;
  }
  fs.writeFileSync(np, nar);
}
console.log(`${deck}: tool-index + ${tools.length} cards; draft "with-index" has ${dj.drafts['with-index'].length} slides`);
