// The four-day schedule as boxes, tagged by topic, for the show-* slides.
// Run from the repo root: node docs/decks/takeaways-v3/theme/gen/schedule.mjs
// Reads kubecon-overview/data/sessions.json (the official schedule pull) and writes
// theme/assets/schedule.js: window.SCHEDULE = { days, counts, talks: [[day, minute, bits], …] }.
// bits: 1 fleet, 2 delivery, 4 AI and agents. A talk counts when its title or abstract (or
// track) matches the topic's pattern below: a keyword match, so the counts are approximate.
import fs from 'node:fs';

const deck = new URL('../../', import.meta.url);
const repo = new URL('../../../', deck);
const sessions = JSON.parse(fs.readFileSync(new URL('kubecon-overview/data/sessions.json', repo), 'utf8'));
const DAYS = ['2026-11-09', '2026-11-10', '2026-11-11', '2026-11-12'];

// [pattern on the title, pattern on the abstract]
const TOPICS = {
  fleet: [
    /multi-?cluster|\bfleet|cluster ?api\b|kubeadm|upgrad|karmada|\bEKS\b|\bGKE\b|\bAKS\b|hundreds of clusters|thousands of (nodes|clusters)|\d[\d,]* (clusters|nodes)|multi-?cloud|hybrid cloud|on-prem|bare[- ]metal|control plane|\betcd\b|karpenter|cluster autoscal|node lifecycle|day[- ]2|cluster lifecycle|kubevirt|edge cluster/i,
    /multi-?cluster|fleet|cluster api|kubeadm|upgrade|karmada|hundreds of clusters|thousands of nodes|\d[\d,]{2,} (clusters|nodes)|multi-?cloud|hybrid cloud|on-premises|bare[- ]metal/i,
  ],
  delivery: [
    /gitops|argo|\bflux|kargo|progressive|canary|rollout|deploy|ci\/cd|\bci\b|pipeline|release|helm|crossplane|platform engineer|golden path|backstage|policy|kyverno|admission|promotion|\bidp\b|internal developer/i,
    /gitops|argo ?cd|argo rollouts|\bflux(cd)?\b|kargo|progressive delivery|canary|ci\/cd|deployment pipeline|helm|crossplane|platform engineering|golden path|backstage|policy[- ]as[- ]code|kyverno|admission control|promotion/i,
  ],
  agents: [
    /\bagent|agentic|\bllm|\bmcp\b|\bai\b|a\.i\.|inference|genai|generative|copilot|model serving|\bgpu|machine learning|\bml\b/i,
    /\bai agents?\b|agentic|\bllms?\b|\bmcp\b|model context protocol|ai[- ]generated|ai[- ]powered|autonomous agent/i,
  ],
};
const BIT = { fleet: 1, delivery: 2, agents: 4 };

const talks = [];
for (const s of sessions) {
  const day = DAYS.indexOf((s.startsAt || '').slice(0, 10));
  if (day < 0 || !(s.speakers || []).length) continue;
  const t = s.title || '', d = s.description || '', tracks = (s.tracks || []).join(' ');
  let bits = 0;
  for (const [k, [rt, rd]] of Object.entries(TOPICS)) if (rt.test(t) || rd.test(d)) bits |= BIT[k];
  if (/AI Inference/.test(tracks)) bits |= BIT.agents;
  if (/Platform Engineering|Application Development \+ Delivery/.test(tracks)) bits |= BIT.delivery;
  const [hh, mm] = s.startsAt.slice(11, 16).split(':').map(Number);
  talks.push([day, hh * 60 + mm, bits, s.room || '']);
}
talks.sort((a, b) => a[0] - b[0] || a[1] - b[1] || a[3].localeCompare(b[3]));
const counts = { all: talks.length };
for (const k of Object.keys(BIT)) counts[k] = talks.filter((x) => x[2] & BIT[k]).length;
const perDay = DAYS.map((_, i) => talks.filter((x) => x[0] === i).length);

const out = `// generated by theme/gen/schedule.mjs from kubecon-overview/data/sessions.json; don't edit
window.SCHEDULE = ${JSON.stringify({ days: DAYS, perDay, counts, talks: talks.map(([d, m, b]) => [d, m, b]) })};
`;
fs.mkdirSync(new URL('theme/assets/', deck), { recursive: true });
fs.writeFileSync(new URL('theme/assets/schedule.js', deck), out);
console.log('talks', counts, 'per day', perDay);
